// Builds src/features/together/koreaMapData.ts from Natural Earth admin-1 (public domain):
//   https://github.com/nvkelso/natural-earth-vector → geojson/ne_10m_admin_1_states_provinces.geojson
// Projects the 17 시·도 to a small SVG coordinate space and simplifies them (Douglas–Peucker).
// Run: node scripts/generate-korea-map.mjs <path-to-ne_10m_admin_1_states_provinces.geojson>
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) throw new Error('pass the Natural Earth admin-1 GeoJSON path');
const out = resolve(dirname(fileURLToPath(import.meta.url)), '../src/features/together/koreaMapData.ts');

const LON0 = 124.4, LAT0 = 38.75, LON1 = 132.1, LAT1 = 33.0;
const K = 52;
const COS = Math.cos((36 * Math.PI) / 180);
const project = ([lon, lat]) => [(lon - LON0) * K * COS, (LAT0 - lat) * K];
const W = Math.ceil((LON1 - LON0) * K * COS), H = Math.ceil((LAT0 - LAT1) * K);
const TOLERANCE = 0.35;
const MIN_AREA = 1.2;

function perpDist(p, a, b) {
  const dx = b[0] - a[0], dy = b[1] - a[1];
  const len = Math.hypot(dx, dy) || 1;
  return Math.abs(dy * p[0] - dx * p[1] + b[0] * a[1] - b[1] * a[0]) / len;
}
function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  let max = 0, idx = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const d = perpDist(pts[i], pts[0], pts[pts.length - 1]);
    if (d > max) { max = d; idx = i; }
  }
  if (max <= tol) return [pts[0], pts[pts.length - 1]];
  return [...simplify(pts.slice(0, idx + 1), tol).slice(0, -1), ...simplify(pts.slice(idx), tol)];
}
/** Closed rings: split at the point farthest from the start so both halves have distinct endpoints. */
function simplifyRing(ring, tol) {
  const pts = ring.slice(0, -1);
  let far = 0, max = -1;
  pts.forEach((p, i) => {
    const d = Math.hypot(p[0] - pts[0][0], p[1] - pts[0][1]);
    if (d > max) { max = d; far = i; }
  });
  const a = simplify(pts.slice(0, far + 1), tol);
  const b = simplify([...pts.slice(far), pts[0]], tol);
  return [...a.slice(0, -1), ...b.slice(0, -1)];
}
function area(pts) {
  let a = 0;
  for (let i = 0; i < pts.length; i++) {
    const [x1, y1] = pts[i], [x2, y2] = pts[(i + 1) % pts.length];
    a += x1 * y2 - x2 * y1;
  }
  return a / 2;
}
function centroid(pts) {
  let cx = 0, cy = 0;
  const a = area(pts) || 1;
  for (let i = 0; i < pts.length; i++) {
    const [x1, y1] = pts[i], [x2, y2] = pts[(i + 1) % pts.length];
    const f = x1 * y2 - x2 * y1;
    cx += (x1 + x2) * f;
    cy += (y1 + y2) * f;
  }
  return [cx / (6 * a), cy / (6 * a)];
}
const fmt = (n) => Math.round(n * 10) / 10;

const ISO_TO_KEY = {
  'KR-11': 'seoul', 'KR-26': 'busan', 'KR-27': 'daegu', 'KR-28': 'incheon', 'KR-29': 'gwangju', 'KR-30': 'daejeon',
  'KR-31': 'ulsan', 'KR-50': 'sejong', 'KR-41': 'gyeonggi', 'KR-42': 'gangwon', 'KR-43': 'chungbuk', 'KR-44': 'chungnam',
  'KR-45': 'jeonbuk', 'KR-46': 'jeonnam', 'KR-47': 'gyeongbuk', 'KR-48': 'gyeongnam', 'KR-49': 'jeju',
};

const gj = JSON.parse(readFileSync(src, 'utf8'));
const regions = {};
for (const f of gj.features.filter((x) => x.properties.adm0_a3 === 'KOR')) {
  const key = ISO_TO_KEY[f.properties.iso_3166_2];
  if (!key) continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const rings = [];
  let biggest = null;
  for (const poly of polys) {
    const ring = poly[0].map(project);
    const a = Math.abs(area(ring));
    const isUlleung = key === 'gyeongbuk' && poly[0][0][0] > 130.5;
    if (a < MIN_AREA && !isUlleung) continue;
    const s = simplifyRing(ring, isUlleung ? 0.1 : TOLERANCE);
    if (s.length < 3) continue;
    rings.push(s);
    if (!biggest || a > biggest.a) biggest = { a, ring };
  }
  if (!biggest) throw new Error(`no usable polygon for ${key} (${polys.length} polygons)`);
  const d = rings.map((r) => 'M' + r.map(([x, y]) => `${fmt(x)} ${fmt(y)}`).join('L') + 'Z').join('');
  const [cx, cy] = centroid(biggest.ring);
  regions[key] = { d, cx: fmt(cx), cy: fmt(cy) };
}

const dokdo = project([131.866, 37.241]);
const ts = `// Generated by scripts/generate-korea-map.mjs from Natural Earth admin-1 (public domain). Do not edit by hand.
export const KOREA_MAP_VIEWBOX = { width: ${W}, height: ${H} } as const;

/** Simplified SVG path + label anchor for each 시·도 (equirectangular, lat 33.0–38.75, lon 124.4–132.1). */
export const KOREA_REGION_SHAPES: Record<string, { d: string; cx: number; cy: number }> = ${JSON.stringify(regions, null, 2)};

/** 독도 (경상북도 울릉군) — too small for the dataset, drawn as a marker. */
export const DOKDO = { x: ${fmt(dokdo[0])}, y: ${fmt(dokdo[1])} } as const;
`;
writeFileSync(out, ts);
console.log(`wrote ${out} (${Math.round(ts.length / 1024)} KB), viewBox ${W}x${H}, ${Object.keys(regions).length} regions`);
